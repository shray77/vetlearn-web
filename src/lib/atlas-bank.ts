export function getAtlasEntries(filter?: { modality?: string; species?: string; difficulty?: string }): AtlasEntry[] {
  if (!filter) return ATLAS_BANK;
  return ATLAS_BANK.filter((e) =>
    (!filter.modality || e.modality === filter.modality) &&
    (!filter.species || e.species === filter.species) &&
    (!filter.difficulty || e.difficulty === filter.difficulty)
  );
}

export function getAtlasEntryById(id: string): AtlasEntry | undefined {
  return ATLAS_BANK.find((e) => e.id === id);
}
