export function getOSCEStationsByType(type?: string): OSCEStation[] {
  if (!type || type === 'all') return OSCE_BANK;
  return OSCE_BANK.filter((s) => s.type === type);
}

export function getOSCEStationById(id: string): OSCEStation | undefined {
  return OSCE_BANK.find((s) => s.id === id);
}

